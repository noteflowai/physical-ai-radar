"""Deterministic editorial checks for deep reads (pairadar/editorial.py, docs/editorial-style.md)."""
import unittest

from pairadar import editorial

STYLE = editorial.load_style()

EN_DEEP = """## Deep reads
### 1. Fixture paper A (MemoryNet)
Source: [arXiv 0000.00001](https://arxiv.org/abs/0000.00001) · full text, arXiv HTML v1
**Bottom line** On six real humanoid tasks, adding object-triggered memory lifts success from 36.7% to 88.3% over the same memoryless policy (Table IV). In simulation the gain is 29.1% to 72.6%.
**What is new** Memory is chosen by object events. A segmenter tracks the task objects, and a frame is kept only when one appears, moves or disappears, so a cue that lasts a second survives the robot turning away.
**Limits** One humanoid, twelve tasks, and 30 trials per real task (Sec. V-E); every task is built so that the cue leaves view, which is exactly where memory should help. No code release is mentioned.
**Our take** Worth copying for any mobile robot that turns its head. The uniform-memory ablation, 51.4% against 72.6% in Table III, is the more useful number: frame choice matters more than memory size.
### 2. Fixture paper B (KinLAM)
Source: [arXiv 0000.00002](https://arxiv.org/abs/0000.00002)
**Bottom line** On a public video dataset, KinLAM cuts end-effector error by 19.5% relative to BaselineWM (Table 1), with LPIPS down 11.1%.
**What is new** The latent action is split in two. One half is tied to the robot skeleton and the other carries whatever else moved.
**Limits** Offline video metrics on one dataset; the real-robot agreement in Sec. 5.4 covers four tasks and is shown as a plot without error bars.
**Our take** Useful if you evaluate policies inside a world model. Do not read the 19.5% as a control result: it measures how well the video tracks the arm.
### 3. Fixture paper C (GraphGen)
Source: [arXiv 0000.00003](https://arxiv.org/abs/0000.00003)
**Bottom line** Fine-tuning a planning LLM on GraphGen data raises success by 12.33 points over the same model tuned on BaseGen data (Table 3).
**What is new** Planner failures are fed back to repair the generated scene graphs. Unsolvable scenes are fixed rather than thrown away.
**Limits** All results are in a symbolic PDDL setting with no robot in the loop; the evaluation set is generated by a similar pipeline, which flatters any generator.
**Our take** A sensible data recipe, but the gain is measured against one generator. We would wait for a test on human-written tasks.
## Also today
- [R] [Fixture paper D](https://arxiv.org/abs/0000.00004): an offline proxy for policy success, checked on simulated benchmarks only.
- [R] [Swarm control](https://arxiv.org/abs/0000.00005): reports 1-10 ms per-agent inference; no hardware trial.
- [R] [Tremor device](https://arxiv.org/abs/0000.00006): a 3-DoF compensation device renders forces up to 4 Hz in bench tests.
- [O] [Retail roundup](https://example.org/retail): a vendor's customer showcase, not a technical result.
- [M] [Startup raise](https://example.org/raise): $100M for a vision-force-action model; no benchmark is public.
"""


class CheckerTest(unittest.TestCase):
    def test_a_professional_english_day_passes(self):
        report = editorial.check(EN_DEEP, "en", STYLE)
        self.assertTrue(report["passed"], report)
        self.assertEqual([d["triples"] >= 1 for d in report["deep"]], [True, True, True])
        self.assertEqual(report["banned_total"], 0)

    def test_stock_phrases_template_sentences_and_missing_parts_fail(self):
        bad = EN_DEEP.replace("Worth copying for any", "It is worth noting that this is a game-changer for any") \
                     .replace("**Limits** Offline video metrics", "**Offline** video metrics")
        report = editorial.check(bad, "en", STYLE)
        self.assertFalse(report["passed"])
        first, second = report["deep"][0]["findings"], report["deep"][1]["findings"]
        self.assertIn("stock phrase(s): it is worth noting, game-changer", first)
        self.assertIn("missing part(s): Limits", second)

    def test_the_old_template_is_caught_by_banned_phrases_and_repetition(self):
        old = ("The visible excerpt only gives background and the page gives no figures; read the paper first "
               "before cutting demonstration data, as it is still a self-reported preprint.")
        lines = "\n".join(f"- [R] [Paper {i}](https://arxiv.org/abs/0000.0000{i}): {old}" for i in range(5))
        report = editorial.check(EN_DEEP.split("## Also today")[0] + "## Also today\n" + lines, "en", STYLE)
        self.assertFalse(report["passed"])
        self.assertGreater(report["template_rate"], 0.15)
        self.assertTrue(all(any("stock phrase" in f for f in i["findings"]) for i in report["index"]))

    def test_a_number_needs_its_baseline_and_a_locator(self):
        text = EN_DEEP.replace(" over the same memoryless policy (Table IV)", "").replace(
            "The uniform-memory ablation, 51.4% against 72.6% in Table III, is", "The ablation is")
        report = editorial.check(text, "en", STYLE)
        self.assertIn("no sentence with a number + unit, its baseline and a source locator (Table/Fig./Sec./p.)",
                      report["deep"][0]["findings"])

    def test_the_bottom_line_must_open_with_a_comparison(self):
        text = EN_DEEP.replace("**Bottom line** On six real", "**Bottom line** Humanoids forget things. On six real")
        self.assertIn("Bottom line: first sentence has no number with a comparison",
                      editorial.check(text, "en", STYLE)["deep"][0]["findings"])

    def test_counts_emoji_and_long_index_lines(self):
        text = EN_DEEP.replace("Worth copying", "Worth copying \U0001F680").replace(
            "- [O] [Retail roundup](https://example.org/retail): a vendor's customer showcase, not a technical result.\n", "")
        text = text.replace("no benchmark is public.", "no benchmark is public " + "and more " * 30 + ".")
        report = editorial.check(text, "en", STYLE)
        self.assertIn("emoji", report["deep"][0]["findings"])
        self.assertIn("4 index line(s), expected 5", report["day"])
        self.assertIn("index line too long", report["index"][-1]["findings"])

    def test_chinese_and_japanese_labels_units_and_banned_lists(self):
        zh = """## 深读
### 1. MemoryNet（示例）
**结论** 在 6 个真实人形机器人任务上，加入按物体事件选帧的记忆后，成功率从 36.7% 提到 88.3%（表 IV），对照组是同一个无记忆策略。
**新在哪里** 记忆由物体事件触发：分割模型跟踪任务物体，只在物体出现、移动或消失时留帧。
**边界** 只有一种人形机器人、十二个任务，每个真实任务 30 次试验（第 V-E 节）；任务都刻意让线索离开视野，正是记忆最占便宜的场景。论文没有提代码是否开源。
**我们的判断** 值得借鉴。更有用的数字是表 III 的均匀记忆消融：51.4% 对 72.6%，说明选对帧比多存帧重要。
## 另外
- [R] [一条](https://arxiv.org/abs/0000.00009)：台架测试。
"""
        report = editorial.check(zh, "zh", STYLE, deep_count=1, index_count=1)
        self.assertTrue(report["passed"], report)
        banned = zh.replace("值得借鉴。", "值得注意的是，这是革命性的。")
        self.assertIn("stock phrase(s): 值得注意的是, 革命性",
                      editorial.check(banned, "zh", STYLE, deep_count=1, index_count=1)["deep"][0]["findings"])
        ja = """## 深掘り
### 1. MemoryNet（例）
**結論** 実機のヒューマノイドで 6 タスクを試したところ、物体イベントで選んだ記憶を加えると成功率は同じ記憶なしの方策と比べ 36.7% から 88.3% に上がった（表 IV）。
**新しい点** 記憶は物体の出現・移動・消失で選ばれる。視野から外れた一瞬の手がかりも残る。
**限界** ヒューマノイドは 1 機種、タスクは 12、実機は各 30 試行（第 V-E 節）。手がかりが視野から外れるよう設計された課題ばかりで、記憶が最も効く条件に偏っている。
**私たちの判断** 首を振る移動ロボットなら参考になる。表 III の一様記憶との比較（51.4% 対 72.6%）の方が、記憶の量より選び方が効くことをよく示している。
## ほかに
- [M] [一件](https://example.org/x)：二次報道。
"""
        self.assertTrue(editorial.check(ja, "ja", STYLE, deep_count=1, index_count=1)["passed"])
        self.assertIn("stock phrase(s): 画期的な",
                      editorial.check(ja.replace("参考になる。", "画期的な成果だ。"), "ja", STYLE,
                                      deep_count=1, index_count=1)["deep"][0]["findings"])

    def test_locators_need_a_numbered_target(self):
        locator = __import__("re").compile(STYLE["locators"])
        for good in ("Table 2", "TABLE II", "Fig. 4", "Sec. IV-C", "Sec. 3.2", "App. B.5", "表 II", "图 4", "図 3",
                     "第 3.2 节", "第 V-E 节", "第 4 节"):
            self.assertTrue(locator.search(good), good)
        for bad in ("the page is", "Figure out", "a table of results", "section heading", "第一次"):
            self.assertFalse(locator.search(bad), bad)

    def test_named_statistics_count_as_measured_numbers(self):
        """Pilot day 1: a correlation has no unit but is a measurement with a baseline and a locator."""
        sentence = "S2 correlates with success at r = +0.681, compared with r = -0.154 for VQA scores (Sec. 3.2)."
        self.assertEqual(editorial.triples(sentence, "en", STYLE), [sentence])
        self.assertEqual(editorial.triples("Correlation is 0.681 compared with 0.154 (Sec. 3.2).", "en", STYLE), [])
        zh = "S² 与成功率的相关系数 r = +0.681，相比 VQA 分数的 r = -0.154（第 3.2 节）。"
        self.assertEqual(len(editorial.triples(zh, "zh", STYLE)), 1)
        self.assertEqual(len(editorial.triples("Spearman ρ = 0.53 against 0.21 for the baseline (App. C).",
                                               "en", STYLE)), 1)

    def test_index_length_counts_the_sentence_not_the_title(self):
        title = "A Transparent 3-DoF Assistive Device: Design and Experimental Validation"
        link = f"[R] [{title}](https://arxiv.org/abs/0000.00006)"
        self.assertEqual(editorial.check_index(f"{link}：台架测试中力反馈带宽达 4 Hz。", "zh", STYLE), [])
        self.assertEqual(editorial.check_index(f"{link}: " + "word " * 41, "en", STYLE), ["index line too long"])
        self.assertIn("index line too long", editorial.check_index(f"{link}：" + "无标题" * 30, "zh", STYLE))

    def test_index_lines_keep_their_link_and_evidence_tag(self):
        """05 (pilot day 1 blind review): the old page let readers open every item and see its grade."""
        self.assertEqual(editorial.check_index("[O] [Post](https://example.org/p): first-party blog.", "en", STYLE), [])
        self.assertEqual(editorial.check_index("`[M]` [Post](https://example.org/p): secondary.", "en", STYLE), [])
        self.assertEqual(editorial.check_index("[R] Post: no link.", "en", STYLE),
                         ["index line has no link to its source"])
        self.assertEqual(editorial.check_index("[Post](https://example.org/p): no tag.", "en", STYLE),
                         ["index line does not start with its evidence tag [O]/[R]/[M]"])
        self.assertIn("index line does not start with its evidence tag [O]/[R]/[M]",
                      editorial.check_index("[X] [Post](https://example.org/p): wrong tag.", "en", STYLE))

    def test_decimal_points_do_not_split_sentences(self):
        self.assertEqual(editorial.sentences("Up from 29.1% to 72.6% in sim. Then 88.3% on G1."),
                         ["Up from 29.1% to 72.6% in sim.", "Then 88.3% on G1."])
        self.assertEqual(editorial.sentences("See Sec. 3.2 and Fig. 4 (Smith et al. 2025). Next one."),
                         ["See Sec. 3.2 and Fig. 4 (Smith et al. 2025).", "Next one."])
        # NFKC: full-width stops become their ASCII forms before splitting.
        self.assertEqual(editorial.sentences("成功率从 36.7% 提到 88.3%。另一句！"), ["成功率从 36.7% 提到 88.3%。", "另一句!"])

    def test_the_style_file_is_versioned_and_complete(self):
        for key in ("deep_parts", "banned"):
            self.assertEqual(set(STYLE[key]), {"zh", "en", "ja"})
        self.assertTrue(all(len(parts) == 4 for parts in STYLE["deep_parts"].values()))
        self.assertTrue(all(len(phrases) >= 15 for phrases in STYLE["banned"].values()))


if __name__ == "__main__":
    unittest.main()
